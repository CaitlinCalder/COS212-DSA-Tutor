const challenge = (
  prompt: string,
  options: string[],
  answer: string,
  explanation: string,
  hints: [string, string, string],
  extras: Pick<QuestChallenge, "queue" | "highlightedRoute" | "routeDestination" | "feedbackReplayStep"> = {},
): QuestChallenge => ({
  prompt,
  options,
  answer,
  explanation,
  hints,
  ...extras,
});

